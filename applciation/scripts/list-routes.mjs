// Generates docs/ROUTES.md from the route files, so the index can never drift from the code.   npm run docs:routes
import { readdirSync, readFileSync, writeFileSync, mkdirSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";

const root = "app/api";
const files = [];
(function walk(d) { for (const n of readdirSync(d)) { const p = join(d, n); statSync(p).isDirectory() ? walk(p) : n === "route.ts" && files.push(p); } })(root);

const rows = [];
for (const f of files.sort()) {
  const src = readFileSync(f, "utf8");
  const path = "/" + relative("app", f).split(sep).slice(0, -1).join("/").replace(/\[(\w+)\]/g, ":$1");
  // option objects declared once and reused: const R = { roles: [...], module: "X" }
  const named = Object.fromEntries([...src.matchAll(/const (\w+)\s*=\s*(\{[^;]*?\})(?: as const)?;/gs)].map((m) => [m[1], m[2]]));
  const seen = new Set();
  for (const m of src.matchAll(/(?:export )?const (GET|POST|PUT|PATCH|DELETE|adminRun) = (route|studentRoute|recruiterRoute)(?:<[^>]*>)?\(\s*/g)) {
    const [, name, wrapper] = m;
    let optRaw = "";
    const at = m.index + m[0].length;
    if (src[at] === "{") { let depth = 0, i = at; do { if (src[i] === "{") depth++; else if (src[i] === "}") depth--; i++; } while (depth > 0 && i < src.length); optRaw = src.slice(at, i); }
    else optRaw = /^\w+/.exec(src.slice(at))?.[0] ?? "";
    const opts = optRaw.startsWith("{") ? optRaw : named[optRaw] ?? "";
    const roles = /roles:\s*\[([^\]]*)\]/.exec(opts)?.[1].replace(/"/g, "").replace(/\s+/g, "").split(",").filter(Boolean);
    const module = /module:\s*"(\w+)"/.exec(opts)?.[1] ?? "";
    const limit = /limit:\s*\{\s*name:\s*"[^"]*",\s*max:\s*(\d+),\s*windowSec:\s*(\d+)/.exec(opts);
    const who = wrapper === "studentRoute" ? "student" : wrapper === "recruiterRoute" ? "recruiter" : roles?.length ? roles.map((r) => r.replace("TPO_ADMIN", "admin").replace("PLACEMENT_OFFICER", "officer").replace("DEPARTMENT_COORDINATOR", "coordinator")).join(", ") : "any staff";
    const method = name === "adminRun" ? "POST" : name;
    seen.add(method);
    rows.push({ method, path, who, module, limit: limit ? `${limit[1]}/${limit[2] >= 3600 ? Math.round(limit[2] / 3600) + "h" : limit[2] + "s"}` : "" });
  }
  for (const m of src.matchAll(/export async function (GET|POST|PUT|PATCH|DELETE)\b/g)) {
    const method = m[1];
    const cron = /isCronRequest/.test(src);
    if (seen.has(method) && !cron) continue;
    if (cron && method === "GET") rows.push({ method, path, who: "scheduler (cron secret)", module: "", limit: "" });
    else if (cron && method === "POST" && !seen.has("POST")) rows.push({ method, path, who: "scheduler (cron secret)", module: "", limit: "" });
    else if (!cron) rows.push({ method, path, who: path === "/api/health" ? "public" : path.startsWith("/api/showcase/") ? "public (link token)" : "public", module: path.startsWith("/api/showcase/") ? "TALENT_SHOWCASE" : "", limit: path.startsWith("/api/showcase/") ? "120/60s per IP" : "" });
  }
}
const order = (p) => p.split("/")[2] === "student" ? "~" + p : p.split("/")[2] === "recruiter" ? "}" + p : p;
rows.sort((a, b) => order(a.path).localeCompare(order(b.path)) || a.method.localeCompare(b.method));
const group = (p) => (p.split("/")[2] === "student" ? "Student app" : p.split("/")[2] === "recruiter" ? "Recruiter portal" : "Staff and system");
let md = `# API route index\n\nGenerated by \`npm run docs:routes\` from the route files (${rows.length} endpoints). Do not edit by hand.\n\n` +
  `- **Who** is the role allowed to call it. "any staff" means any signed-in staff member; department coordinators only ever see their own department's students.\n` +
  `- **Module** is the paid module that must be enabled for the college; blank means core.\n` +
  `- **Limit** is the per-user rate limit (requests per window) where one is set.\n` +
  `- Every response is JSON \`{ "data": ... }\` or \`{ "error": { "code", "message", "details?", "requestId" } }\`, except file downloads (Excel / PDF).\n` +
  `- Send \`Authorization: Bearer <Supabase access token>\`. Lists use \`?limit=&cursor=\` and return \`{ items, nextCursor }\`.\n`;
for (const g of ["Staff and system", "Student app", "Recruiter portal"]) {
  md += `\n## ${g}\n\n| Method | Path | Who | Module | Limit |\n|---|---|---|---|---|\n`;
  for (const r of rows.filter((x) => group(x.path) === g)) md += `| ${r.method} | \`${r.path}\` | ${r.who} | ${r.module} | ${r.limit} |\n`;
}
mkdirSync("docs", { recursive: true });
writeFileSync("docs/ROUTES.md", md);
console.log(`docs/ROUTES.md: ${rows.length} endpoints`);
